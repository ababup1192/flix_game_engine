var testMarkers = CoreMarkers{Begin: "<!-- core -->", End: "<!-- /core -->"}

// 芯の印で囲った所だけを、並びのまま空行 1 つでつなぎ、末尾に more を付ける。
func TestExtractCoreKeepsOnlyMarkedRegions(t *testing.T) {
	doc := "# 題\n<!-- core -->\nA\n\n<!-- /core -->\n外 1\n<!-- core -->\nB\n<!-- /core -->\n外 2\n"
	got, ok := extractCore(doc, testMarkers, "詳しくは X")
	if !ok {
		t.Fatal("印の組があるのに失敗した")
	}
	if want := "A\n\nB\n\n詳しくは X\n"; got != want {
		t.Errorf("got %q want %q", got, want)
	}
}

// 印が無い・閉じていない doc は芯を作れない（全文へ黙って倒さない）。
func TestExtractCoreRejectsBrokenMarkers(t *testing.T) {
	for _, doc := range []string{"印なし\n", "<!-- core -->\n閉じない\n", "<!-- /core -->\n開かない\n"} {
		if _, ok := extractCore(doc, testMarkers, "x"); ok {
			t.Errorf("壊れた印を受け入れた: %q", doc)
		}
	}
}

// more のあるルールの元 doc から印が消えたら、生成は止まる。
func TestMissingCoreMarkersStops(t *testing.T) {
	spec := flixSpec(t)
	if spec.More == "" {
		t.Skip("flix.md に more が無い")
	}
	docs := allDocs(t)
	docs[spec.Src] = "# 印の無い全文\n"
	root := fixture(t, docs)
	var out, errOut strings.Builder
	code, err := Run(&out, &errOut, root, nil, Options{})
	if err == nil || code == 0 {
		t.Fatalf("印の無い doc で止まらなかった: code=%d", code)
	}
}
