// fixture は使い捨ての配り元を作る。規約データだけはリポの物を写す。
func fixture(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	rules, err := os.ReadFile(filepath.Join(repoRoot(), RulesPath))
	if err != nil {
		t.Fatal(err)
	}
	write(t, root, RulesPath, string(rules), 0o644)
	write(t, root, "agents-pack/AGENTS.core.md", "# core\n\n本文\n\n\n", 0o644)
	write(t, root, "agents-pack/skills/alpha/SKILL.md",
		"---\nname: alpha\ndescription: \"能書き。〜のときに使う。補足。\"\n---\n", 0o644)
	write(t, root, "agents-pack/skills/beta/SKILL.md",
		"---\ndescription: 引き金の無い説明。おまけ。\n---\n", 0o644)
	if err := os.MkdirAll(filepath.Join(root, "agents-pack", "skills", "gamma"), 0o755); err != nil {
		t.Fatal(err)
	}
	write(t, root, "agents-pack/rules/b.md", ".claude/skills/alpha/SKILL.md\n", 0o644)
	write(t, root, "agents-pack/rules/a.md", "x\n", 0o644)
	write(t, root, "docs/link.md", ".claude/skills/nope/SKILL.md\n", 0o644)
	write(t, root, "bin/lint-fake.py", "#!/usr/bin/env python3\n", 0o755)
	write(t, root, "bin/plain.txt", "y\n", 0o644)
	write(t, root, "agents-pack/manifest.json", `{
	  "copy": [{"src": "bin/lint-fake.py", "dst": "bin/lint-fake.py"},
	           {"src": "bin/plain.txt", "dst": "bin/plain.txt"}],
	  "copyIfAbsent": [{"src": "bin/plain.txt", "dst": ".claude/settings.json"}],
	  "copyDirs": [{"src": "agents-pack/skills", "dst": ".claude/skills"}]
	}`, 0o644)
	return root
}

func write(t *testing.T, root, rel, body string, mode os.FileMode) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), mode); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(path, mode); err != nil {
		t.Fatal(err)
	}
}

func run(t *testing.T, root string, args ...string) (string, string, int) {
	t.Helper()
	var out, errOut strings.Builder
	code, err := Run(&out, &errOut, root, args)
	if err != nil {
		t.Fatalf("止まってしまった: %v", err)
	}
	return out.String(), errOut.String(), code
}

func TestSyncWritesAgentsMd(t *testing.T) {
	root := fixture(t)
	game := t.TempDir()
	out, errOut, code := run(t, root, "--game", game, "--version", "1.2.3")
	if code != 0 || errOut != "" {
		t.Fatalf("code=%d err=%q", code, errOut)
	}
	if !strings.Contains(out, "[sync-agents] skill: alpha\n") {
		t.Errorf("skill の一覧が出ていない: %q", out)
	}
	body, err := os.ReadFile(filepath.Join(game, "AGENTS.md"))
	if err != nil {
		t.Fatal(err)
	}
	want := "<!-- generated by flix_game_engine agents-pack (engine v1.2.3)." +
		" 編集しないで。共通部は engine の agents-pack/AGENTS.core.md、" +
		"ゲーム固有部は AGENTS.local.md を編集して再 sync -->\n\n" +
		"# core\n\n本文\n\n" +
		"## 配られているスキル一覧（sync-agents が自動生成。手で編集しない）\n\n" +
		"- `.claude/skills/alpha/SKILL.md` — 〜のときに使う。\n" +
		"- `.claude/skills/beta/SKILL.md` — 引き金の無い説明。\n" +
		"- `.claude/skills/gamma/SKILL.md` — \n"
	if string(body) != want {
		t.Errorf("AGENTS.md が\n%q\n期待\n%q", string(body), want)
	}
}

