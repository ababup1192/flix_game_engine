package px

// 字形の組（text の font・形 text の font）。'#' が字の画素。小文字は大文字で引く（組に小文字があればそれ）。

import (
	"fmt"
	"sort"
	"strings"
	"unicode"

	"github.com/ababup1192/flix_game_engine/go/internal/pxlib"
)

// pxFont は字形の組 1 つ。
type pxFont struct {
	W, H          int
	Advance, Line int // 既定の字の送りと行の送り
	Summary       string
	Glyphs        map[rune][]string
}

// fonts は字形の組の表（名前 → 組）。
var fonts = map[string]*pxFont{}

func init() {
	small := map[rune][]string{}
	for r, g := range font5x7 {
		small[r] = g[:]
	}
	fonts["5x7"] = &pxFont{W: 5, H: 7, Advance: 6, Line: 9, Glyphs: small, Summary: "5×7・線 1px（町の名前のラベル・看板・小さい HUD）"}
	fonts["bold6x8"] = &pxFont{W: 6, H: 8, Advance: 7, Line: 10, Glyphs: fontBold6x8, Summary: "6×8・線 2px の太い字（16 bit 機のスコア・HUD。塗りと縁は形 text に gradient_fill・outline）"}
}

// fontNames は字形の組の名前（説明の字面用）。
func fontNames() string {
	names := make([]string, 0, len(fonts))
	for n := range fonts {
		names = append(names, n)
	}
	sort.Strings(names)
	return strings.Join(names, "・")
}

// layoutText は文字列を字形の組で並べた画素（1 字目の左上が at）を返す。advance・line が 0 なら組の既定。
func layoutText(fontName, text string, at pxlib.Pt, advance, line int) ([]pxlib.Pt, error) {
	f, ok := fonts[fontName]
	if !ok {
		return nil, fmt.Errorf("知らない字形の組 %q（%s）", fontName, fontNames())
	}
	if advance <= 0 {
		advance = f.Advance
	}
	if line <= 0 {
		line = f.Line
	}
	var out []pxlib.Pt
	x, y := at.X, at.Y
	for _, ch := range text {
		if ch == '\n' {
			x, y = at.X, y+line
			continue
		}
		g, ok := f.Glyphs[ch]
		if !ok {
			g, ok = f.Glyphs[unicode.ToUpper(ch)]
		}
		if !ok && ch != ' ' {
			return nil, fmt.Errorf("字 %q は字形に無い（組 %s。英大文字・数字・. , ! ? - + : ' / x * %%。ほかは glyph_rows か形 mask で置く）", string(ch), fontName)
		}
		for dy, row := range g {
			for dx, r := range row {
				if r == '#' {
					out = append(out, pxlib.Pt{X: x + dx, Y: y + dy})
				}
			}
		}
		x += advance
	}
	return out, nil
}

