order = ['ru','bar','ne','no','izumi']
S = 2
gap = 2
def grid(s):
    rows = [r for r in s.strip('\n').split('\n')]
    return rows
gl = [grid(G[k]) for k in order]
H = max(len(g) for g in gl)*S
W = sum(len(g[0])*S for g in gl) + gap*(len(gl)-1)
pad = 2
TW, TH = W + pad*2, H + pad*2
fill = [[False]*TW for _ in range(TH)]
x0 = pad
for g in gl:
    w = len(g[0])
    for r,row in enumerate(g):
        for c,ch in enumerate(row):
            if ch == '#':
                for dy in range(S):
                    for dx in range(S):
                        fill[pad + r*S+dy][x0 + c*S+dx] = True
    x0 += w*S + gap
out = [['.']*TW for _ in range(TH)]
for y in range(TH):
    for x in range(TW):
        if fill[y][x]:
            t = (y - pad) / H
            out[y][x] = 'y' if t < 0.34 else ('o' if t < 0.70 else 'r')
# ink outline: 8-neighbour 1px, plus drop shadow 1px down-right
for y in range(TH):
    for x in range(TW):
        if fill[y][x]: continue
        hit = False
        for dy in (-1,0,1):
            for dx in (-1,0,1):
                yy, xx = y+dy, x+dx
                if 0<=yy<TH and 0<=xx<TW and fill[yy][xx]: hit = True
        # shadow: pixel 2 up-left is fill
        for (dy,dx) in ((-2,-2),(-2,-1),(-1,-2)):
            yy, xx = y+dy, x+dx
            if 0<=yy<TH and 0<=xx<TW and fill[yy][xx]: hit = True
        if hit: out[y][x] = 'k'
# trim empty rows/cols
rows = [''.join(r) for r in out]
while rows and set(rows[-1]) == {'.'}: rows.pop()
while rows and set(rows[0]) == {'.'}: rows.pop(0)
logo = rows
for r in logo: print(r, file=sys.stderr)

