def build_char(c, dirn, f):
    cv = blank()
    up = c["upper"][dirn]
    leg_dir = "down" if dirn in ("down", "up") else "left"
    lg = [r.replace("L", c["leg"]) for r in LEGS[c["legs"]][leg_dir][f]]
    ly = 16 - len(lg)
    put(cv, lg, c.get("legs_dx", {}).get(dirn, 0), ly)
    put(cv, up, 0, 0)
    return rows(cv)

def frames_for(c):
    out = {}
    for f in (0, 1):
        for dirn in ("down", "up", "left"):
            if dirn in c["upper"]:
                out[f"{dirn}_{f}"] = build_char(c, dirn, f)
        out[f"right_{f}"] = mirror(out[f"left_{f}"])
    order = ["down_0", "down_1", "up_0", "up_1", "left_0", "left_1", "right_0", "right_1"]
    for k, rs in out.items():
        for r in rs:
            if len(r) != 16:
                raise SystemExit(f"幅が 16 でない: {k} {r!r}")
    return {k: out[k] for k in order if k in out}

for _n, _c in CH.items():
    for _d, _u in _c["upper"].items():
        for _r in _u:
            if len(_r) != 16:
                raise SystemExit(f"{_n}.{_d}: 幅 {len(_r)}: {_r!r}")
        _nl = len(LEGS[_c["legs"]]["down"][0])
        if len(_u) != 16 - _nl:
            raise SystemExit(f"{_n}.{_d}: 行数 {len(_u)} != {16 - _nl}")
