import colorsys, json, os

# 素材ごとのランプ（明るい → 暗い）。(色相°, 彩度, 明度)
ramps = {
    # A キャラ
    "coat":  [(54, .35, .98), (46, .78, .95), (34, .85, .78), (20, .80, .55)],
    "skin":  [(30, .25, .98), (18, .40, .86)],
    "hair":  [(24, .60, .55), (8, .62, .36)],
    "boot":  [(205, .45, .50), (222, .55, .32)],
    "glow":  [(52, .30, 1.0)],
    "ink":   [(300, .45, .17)],
    # B タイル
    "grass": [(78, .55, .78), (98, .60, .62), (125, .58, .45), (160, .60, .30)],
    "dirt":  [(32, .42, .66), (22, .50, .50), (10, .52, .34)],
    "stone": [(40, .08, .76), (36, .09, .60), (230, .10, .44), (240, .14, .30)],
    "water": [(186, .40, .86), (198, .62, .70), (214, .70, .52), (232, .70, .35)],
    # C 場面
    "night": [(238, .40, .24), (250, .45, .14)],
    "wall":  [(215, .22, .42), (225, .28, .32), (235, .32, .22)],
    "wood":  [(36, .55, .80), (26, .62, .62), (14, .65, .42), (358, .62, .26)],
    "lamp":  [(50, .35, 1.0), (36, .80, 1.0), (10, .85, .85), (352, .75, .55)],
    "iron":  [(250, .12, .42), (260, .18, .28), (270, .25, .16)],
    "steam": [(220, .06, .92), (225, .12, .74), (232, .18, .54)],
    "imo":   [(320, .45, .60), (300, .50, .38)],
    "litwall": [(22, .38, .52)],
}

pal = {}
for n, r in ramps.items():
    for i, (h, s, v) in enumerate(r):
        rgb = colorsys.hsv_to_rgb((h % 360) / 360, s, v)
        pal[f"{n}{i}"] = {"rgb": [round(c, 3) for c in rgb]}
        print(f"{n}{i}", "#%02x%02x%02x" % tuple(int(c * 255) for c in rgb))

out = os.path.join(os.path.dirname(__file__), "..", "assets", "palette.json")
with open(out, "w") as f:
    json.dump(pal, f, indent=1)
